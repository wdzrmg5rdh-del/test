const BITMAPS = new Map<string, Uint8Array>();
for (const [ch, def] of Object.entries(GLYPHS)) {
  const rows = def.split('|');
  const bm = new Uint8Array(35);
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) bm[y * 5 + x] = rows[y][x] === '#' ? 1 : 0;
  BITMAPS.set(ch, bm);
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;
export const LINE_H = 10;

export interface TextOpts {
  scale?: number;
  align?: 'left' | 'center' | 'right';
  shadow?: number;
}

function normalize(text: string): string {
  return text.toUpperCase();
}

export function measureText(text: string, scale = 1): number {
  const t = normalize(text);
  if (t.length === 0) return 0;
  return (t.length * ADVANCE - 1) * scale;
}

function drawRaw(s: Surface, t: string, x: number, y: number, c: number, scale: number): void {
  let cx = x;
  for (const ch of t) {
    const bm = BITMAPS.get(ch) ?? BITMAPS.get('?')!;
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (bm[gy * 5 + gx]) {
          if (scale === 1) s.pset(cx + gx, y + gy, c);
          else s.fillRect(cx + gx * scale, y + gy * scale, scale, scale, c);
        }
      }
    }
    cx += ADVANCE * scale;
  }
}

/** Zeichnet Text; y ist die Oberkante der Glyphen. */
export function drawText(s: Surface, text: string, x: number, y: number, color: number, opts: TextOpts = {}): void {
  const scale = opts.scale ?? 1;
  const t = normalize(text);
  const w = measureText(t, scale);
  let sx = Math.round(x);
  if (opts.align === 'center') sx = Math.round(x - w / 2);
  else if (opts.align === 'right') sx = Math.round(x - w);
  const sy = Math.round(y);
  if (opts.shadow !== undefined) drawRaw(s, t, sx + scale, sy + scale, opts.shadow, scale);
  drawRaw(s, t, sx, sy, color, scale);
}

/** Bricht Text an Leerzeichen um, sodass jede Zeile höchstens maxChars Zeichen hat. */
export function wrapText(text: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (line.length === 0) line = word;
      else if (line.length + 1 + word.length <= maxChars) line += ' ' + word;
      else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
